// Finds conflicting Tailwind classes (two classes on one element that set the
// same CSS properties under the same variant), like the Tailwind CSS
// IntelliSense "cssConflict" lint, but for the whole project and with the
// project's own Tailwind v3 config.
//
// Usage: pnpm lint:classes      (exit code 1 when conflicts are found)
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import config from "../tailwind.config.js";

const root = fileURLToPath(new URL("..", import.meta.url));

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (name !== "__tests__") yield* walk(path);
    } else if (/\.(vue|js)$/.test(name)) {
      yield path;
    }
  }
}

/** Class lists that end up on one element: static `class="…"` and each string literal in `:class`. */
function classLists(source) {
  const lists = [];
  const lineOf = (index) => source.slice(0, index).split("\n").length;
  for (const m of source.matchAll(/(?<![:\w-])class="([^"]*)"/g)) {
    lists.push({ line: lineOf(m.index), classes: m[1] });
  }
  for (const m of source.matchAll(/:class="([^"]*)"/g)) {
    for (const s of m[1].matchAll(/'([^']*)'|`([^`$]*)`/g)) {
      lists.push({ line: lineOf(m.index), classes: s[1] ?? s[2] });
    }
  }
  return lists
    .map((l) => ({ ...l, classes: [...new Set(l.classes.split(/\s+/).filter(Boolean))] }))
    .filter((l) => l.classes.length > 1);
}

// Our own utilities (e.g. min-h-app) generate nothing here: silence Tailwind's
// "No utility classes were detected" warning. This script reports via log/error.
console.warn = () => {};

const cache = new Map();

/** For one class: "context → sorted property list", generated by Tailwind itself. */
async function signature(cls) {
  if (cache.has(cls)) return cache.get(cls);
  const result = await postcss([
    tailwindcss({ ...config, content: [{ raw: ` ${cls} ` }], corePlugins: { preflight: false } }),
  ]).process("@tailwind utilities;", { from: undefined });

  const contexts = new Map();
  result.root.walkRules((rule) => {
    const props = [];
    rule.walkDecls((decl) => props.push(decl.prop));
    if (!props.length) return;
    let atRules = "";
    for (let p = rule.parent; p && p.type === "atrule"; p = p.parent) atRules = `@${p.name} ${p.params} ${atRules}`;
    // Replace this class's escaped selector so variants compare equal across classes.
    const context = atRules + rule.selector.replace(/\.(?:\\.|[^\s\\:>+~,.[()])+/, "&");
    contexts.set(context, [...new Set([...(contexts.get(context) ?? []), ...props])].sort().join(","));
  });
  cache.set(cls, contexts);
  return contexts;
}

const problems = [];
const files = [join(root, "index.html"), ...walk(join(root, "src"))];

for (const file of files) {
  const source = readFileSync(file, "utf8");
  for (const { line, classes } of classLists(source)) {
    const sigs = await Promise.all(classes.map(signature));
    for (let a = 0; a < classes.length; a++) {
      for (let b = a + 1; b < classes.length; b++) {
        for (const [context, props] of sigs[a]) {
          if (sigs[b].get(context) === props) {
            problems.push(`${relative(root, file)}:${line}  '${classes[a]}' and '${classes[b]}' both set ${props}`);
            break;
          }
        }
      }
    }
  }
}

if (problems.length) {
  console.error(`✗ ${problems.length} conflicting Tailwind class pair(s):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
console.log(`✓ No conflicting Tailwind classes (${files.length} files, ${cache.size} classes checked)`);
